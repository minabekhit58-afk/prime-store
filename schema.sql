-- Run this in Supabase SQL Editor. It is safe to run after the initial tables were created.
-- Do not put the service-role key in browser code or GitHub.

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  description text default '',
  price numeric(10,2) not null default 0 check (price >= 0),
  image_url text default '',
  category text default 'Accessories',
  stock integer not null default 0 check (stock >= 0),
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  customer_name text not null,
  phone text not null,
  address text not null,
  total numeric(10,2) not null default 0,
  status text not null default 'new',
  created_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete cascade,
  product_id bigint references public.products(id) on delete set null,
  product_name text not null,
  quantity integer not null default 1 check (quantity > 0),
  unit_price numeric(10,2) not null default 0
);

alter table public.products enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;

-- Public visitors may read active products only. Server-side admin uses the service-role key.
drop policy if exists "Public can view active products" on public.products;
create policy "Public can view active products"
on public.products for select to anon, authenticated
using (is_active = true);

-- Intentionally no public policies for orders/order_items.
-- The server uses the service-role key for order creation and admin operations.
